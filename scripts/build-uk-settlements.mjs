import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [citiesPath, admin1Path, admin2Path, alternateNamesPath, outputPath] =
  process.argv.slice(2);

if (!citiesPath || !admin1Path || !admin2Path || !alternateNamesPath || !outputPath) {
  console.error(
    "Usage: node scripts/build-uk-settlements.mjs <cities500.txt> <admin1CodesASCII.txt> <admin2Codes.txt> <GB alternate names.txt> <output.js>",
  );
  process.exit(1);
}

const SOURCE_DATE = "2026-08-19";
const SOURCE_URL = "https://download.geonames.org/export/dump/cities500.zip";
const ALTERNATE_NAMES_URL =
  "https://download.geonames.org/export/dump/alternatenames/GB.zip";
const ALLOWED_NATIONS = new Map([
  ["ENG", "England"],
  ["SCT", "Scotland"],
  ["WLS", "Wales"],
  ["NIR", "Northern Ireland"],
]);
const ALLOWED_FEATURE_CODES = new Set([
  "PPL",
  "PPLA",
  "PPLA2",
  "PPLA3",
  "PPLA4",
  "PPLC",
]);
const ALLOWED_ALIAS_LANGUAGES = new Set(["", "en", "cy", "gd", "ga", "sco", "kw"]);

function tabRows(path) {
  return readFileSync(resolve(path), "utf8")
    .split(/\r?\n/)
    .filter(Boolean)
    .map((line) => line.split("\t"));
}

function normaliseSearchText(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/\p{M}/gu, "")
    .toLocaleLowerCase("en-GB")
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

function validAlias(value) {
  const name = String(value || "").trim();
  if (name.length < 2 || name.length > 80) return false;
  return /^[\p{L}\p{M} .()'’\-/]+$/u.test(name);
}

const admin1Names = new Map(
  tabRows(admin1Path).map(([code, name]) => [code, name]),
);
const admin2Names = new Map(
  tabRows(admin2Path).map(([code, name]) => [code, name]),
);

const aliasesById = new Map();
tabRows(alternateNamesPath).forEach((row) => {
  const geonameId = row[1];
  const language = row[2] || "";
  const name = row[3] || "";
  const isHistoric = row[7] === "1";
  if (
    !geonameId ||
    !ALLOWED_ALIAS_LANGUAGES.has(language) ||
    isHistoric ||
    !validAlias(name)
  ) {
    return;
  }
  const aliases = aliasesById.get(geonameId) || [];
  aliases.push({
    name: name.trim(),
    priority: language === "en" ? 0 : language === "" ? 1 : 2,
  });
  aliasesById.set(geonameId, aliases);
});

const settlements = tabRows(citiesPath)
  .filter((row) => {
    const countryCode = row[8];
    const featureCode = row[7];
    const nationCode = row[10];
    return (
      countryCode === "GB" &&
      ALLOWED_NATIONS.has(nationCode) &&
      ALLOWED_FEATURE_CODES.has(featureCode)
    );
  })
  .map((row) => {
    const id = row[0];
    const name = row[1].trim();
    const asciiName = row[2].trim();
    const latitude = Number(row[4]);
    const longitude = Number(row[5]);
    const nationCode = row[10];
    const admin2Code = row[11];
    const country = ALLOWED_NATIONS.get(nationCode);
    const adminArea =
      admin2Names.get(`GB.${nationCode}.${admin2Code}`) ||
      admin1Names.get(`GB.${nationCode}`) ||
      country;
    const population = Math.max(0, Number(row[14]) || 0);
    const canonicalName = normaliseSearchText(name);
    const aliases = [
      ...(asciiName ? [{ name: asciiName, priority: 0 }] : []),
      ...(aliasesById.get(id) || []),
    ]
      .sort((a, b) => a.priority - b.priority || a.name.localeCompare(b.name, "en-GB"))
      .filter((alias, index, list) => {
        const normalized = normaliseSearchText(alias.name);
        if (!normalized || normalized === canonicalName) return false;
        return list.findIndex((item) => normaliseSearchText(item.name) === normalized) === index;
      })
      .slice(0, 12)
      .map((alias) => alias.name);

    return [
      id,
      name,
      adminArea,
      country,
      latitude,
      longitude,
      population,
      aliases,
    ];
  })
  .sort(
    (a, b) =>
      a[1].localeCompare(b[1], "en-GB") ||
      a[2].localeCompare(b[2], "en-GB") ||
      a[0].localeCompare(b[0]),
  );

const nationCounts = settlements.reduce((counts, settlement) => {
  counts[settlement[3]] = (counts[settlement[3]] || 0) + 1;
  return counts;
}, {});

const header = `/*
 * OnSite canonical UK settlement data.
 * Source: GeoNames cities500 and GB alternate-name exports (${SOURCE_DATE}).
 * URLs: ${SOURCE_URL}
 *       ${ALTERNATE_NAMES_URL}
 * Licence: Creative Commons Attribution 4.0 International (CC BY 4.0).
 * Attribution: GeoNames (https://www.geonames.org/).
 * Filters: country GB; constituent nations England, Scotland, Wales and
 * Northern Ireland; feature codes PPL/PPLA/PPLA2/PPLA3/PPLA4/PPLC. Sections,
 * neighbourhoods, historical, abandoned and destroyed places are excluded.
 * Tuple schema: [id, name, adminArea, country, latitude, longitude, population, aliases].
 * Generated by scripts/build-uk-settlements.mjs. Do not edit manually.
 */
`;

const metadata = {
  source: "GeoNames",
  sourceDate: SOURCE_DATE,
  sourceUrl: SOURCE_URL,
  alternateNamesUrl: ALTERNATE_NAMES_URL,
  licence: "CC BY 4.0",
  attributionUrl: "https://www.geonames.org/",
  count: settlements.length,
  nationCounts,
  schema: [
    "id",
    "name",
    "adminArea",
    "country",
    "latitude",
    "longitude",
    "population",
    "aliases",
  ],
};

const rows = settlements.map((settlement) => `    ${JSON.stringify(settlement)}`).join(",\n");
const output = `${header}(function (root, factory) {
  const data = factory();
  if (typeof module === "object" && module.exports) module.exports = data;
  else root.OnSiteUkSettlementData = data;
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  return {
    metadata: ${JSON.stringify(metadata, null, 2).replace(/^/gm, "    ").trimStart()},
    settlements: [
${rows}
    ],
  };
});
`;

writeFileSync(resolve(outputPath), output, "utf8");
console.log(`Wrote ${settlements.length} UK settlements to ${outputPath}`);
console.log(JSON.stringify(nationCounts));
